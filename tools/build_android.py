"""Build the Android tablet app from the shared engine sources.

Everything generated lives below the ignored build/android/. Original game
resources are copied only there. The Swift toolchain and Android SDK used here
are unpacked below build/android too (see docs/android.md); nothing is
installed globally. No original executable is run.
"""
from __future__ import annotations
import argparse
import base64
import json
import struct
import os
from pathlib import Path
import shutil
import subprocess

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "build/android"
TOOLCHAIN_BIN = OUT / "toolchain/swift-6.3-RELEASE-osx-package.pkg/Payload/usr/bin"
SDKS = OUT / "sdks"
TRIPLE = "aarch64-unknown-linux-android28"


def package_sources() -> list[Path]:
    shared = json.loads((ROOT / "iOS/SharedSources.json").read_text())
    files = [ROOT / item for item in shared] + [ROOT / "iOS/IPadGameStore.swift"]
    files += sorted((ROOT / "android/swift").glob("*.swift"))
    if len(set(files)) != len(files) or any(not f.is_file() for f in files):
        raise ValueError("Android source manifest has a missing or repeated file")
    return files


def cp949_table_source() -> str:
    """CP949 (the font's text encoding) as a table, since Android's Foundation has no code page 949."""
    pairs = bytearray()
    for code in range(0x80, 0x10000):
        try:
            raw = chr(code).encode("cp949")
        except UnicodeEncodeError:
            continue
        if len(raw) == 2:
            pairs += struct.pack("<IH", code, raw[0] << 8 | raw[1])
    payload = base64.b64encode(bytes(pairs)).decode()
    return (
        "// Generated by tools/build_android.py. Code page 949 pairs: UInt32 scalar, UInt16 code.\n"
        "import Foundation\n#if os(Android)\nenum CP949 {\n"
        f"    private static let packed = \"{payload}\"\n"
        "    private static let table:[UInt32:UInt16] = {\n"
        "        guard let data = Data(base64Encoded:packed) else {return [:]}\n"
        "        let bytes = [UInt8](data);var out:[UInt32:UInt16] = [:];var i = 0\n"
        "        while i+6 <= bytes.count {\n"
        "            let scalar = UInt32(bytes[i])|UInt32(bytes[i+1])<<8|UInt32(bytes[i+2])<<16|UInt32(bytes[i+3])<<24\n"
        "            out[scalar] = UInt16(bytes[i+4])|UInt16(bytes[i+5])<<8;i += 6\n"
        "        }\n        return out\n    }()\n"
        "    static func encode(_ text:String) -> [UInt8] {\n"
        "        var out:[UInt8] = []\n"
        "        for scalar in text.unicodeScalars {\n"
        "            if scalar.value < 0x80 {out.append(UInt8(scalar.value))}\n"
        "            else if let code = table[scalar.value] {out.append(UInt8(code>>8));out.append(UInt8(code&255))}\n"
        "            else {out.append(0x3F)}\n"
        "        }\n        return out\n    }\n}\n#endif\n")


def generate_package() -> Path:
    pkg = OUT / "pkg"
    sources = pkg / "Sources/yeonggeoljeon"
    if pkg.exists():
        shutil.rmtree(pkg)
    sources.mkdir(parents=True)
    for path in package_sources():
        (sources / path.name).symlink_to(path)
    (sources / "CP949Table.swift").write_text(cp949_table_source())
    (pkg / "Package.swift").write_text(
        "// swift-tools-version:5.9\nimport PackageDescription\n"
        "let package = Package(name: \"yeonggeoljeon\",\n"
        "  products: [.library(name: \"yeonggeoljeon\", type: .dynamic, targets: [\"yeonggeoljeon\"])],\n"
        "  targets: [.target(name: \"yeonggeoljeon\", path: \"Sources/yeonggeoljeon\",\n"
        "    swiftSettings: [.unsafeFlags([\"-Xfrontend\", \"-disable-availability-checking\"])])])\n")
    return pkg


def swift_env() -> dict[str, str]:
    env = dict(os.environ)
    env["PATH"] = f"{TOOLCHAIN_BIN}:{env['PATH']}"
    env["ANDROID_NDK_HOME"] = str(Path.home() / "Library/Android/sdk/ndk/27.3.13750724")
    return env


def build_swift(configuration: str) -> Path:
    pkg = generate_package()
    subprocess.run([str(TOOLCHAIN_BIN / "swift"), "build", "--swift-sdks-path", str(SDKS),
                    "--swift-sdk", TRIPLE, "-c", configuration, "--package-path", str(pkg)],
                   check=True, env=swift_env())
    return pkg / ".build" / TRIPLE / configuration


SDK_HOME = Path.home() / "Library/Android/sdk"
NDK = SDK_HOME / "ndk/27.3.13750724"
NDK_BIN = NDK / "toolchains/llvm/prebuilt/darwin-x86_64/bin"
BUILD_TOOLS = SDK_HOME / "build-tools/35.0.0"
ANDROID_JAR = SDK_HOME / "platforms/android-35/android.jar"
SWIFT_LIBS = SDKS / "swift-6.3-RELEASE_android.artifactbundle/swift-android/swift-resources/usr/lib/swift-aarch64/android"


def run(command: list[str], **kwargs) -> None:
    subprocess.run([str(part) for part in command], check=True, **kwargs)


def needed(library: Path) -> list[str]:
    text = subprocess.run([str(NDK_BIN / "llvm-readelf"), "-d", str(library)], check=True, capture_output=True, text=True).stdout
    return [line.split("[")[1].split("]")[0] for line in text.splitlines() if "NEEDED" in line]


def runtime_libraries(engine: Path, extra: list[Path]) -> list[Path]:
    """The Swift runtime libraries the engine needs, found by following each library's NEEDED entries."""
    found: dict[str, Path] = {}
    pending = [engine, *extra]
    while pending:
        current = pending.pop()
        for name in needed(current):
            if name in found:
                continue
            for folder in (SWIFT_LIBS, NDK / "toolchains/llvm/prebuilt/darwin-x86_64/sysroot/usr/lib/aarch64-linux-android"):
                if name == "libc++_shared.so" and (folder / name).is_file() or name.startswith(("libswift", "libFoundation", "lib_Foundation", "libdispatch", "libBlocksRuntime")) and (folder / name).is_file():
                    found[name] = folder / name
                    pending.append(folder / name)
                    break
    return sorted(found.values())


def build_jni(products: Path) -> Path:
    out = OUT / "jni"
    out.mkdir(parents=True, exist_ok=True)
    library = out / "libygjni.so"
    run([NDK_BIN / "aarch64-linux-android28-clang", "-shared", "-fPIC", "-O2", ROOT / "android/jni/yg_jni.c",
         "-o", library, f"-L{products}", "-lyeonggeoljeon", "-Wl,-rpath,$ORIGIN"])
    return library


def make_icon(out: Path) -> None:
    source = OUT / "icon/AppIcon.png"
    source.parent.mkdir(parents=True, exist_ok=True)
    run(["xcrun", "swift", ROOT / "tools/make_ipad_icon.swift", source])
    for folder, size in (("mipmap-mdpi", 48), ("mipmap-hdpi", 72), ("mipmap-xhdpi", 96), ("mipmap-xxhdpi", 144), ("mipmap-xxxhdpi", 192)):
        target = out / "res" / folder
        target.mkdir(parents=True, exist_ok=True)
        run(["sips", "-z", str(size), str(size), source, "--out", target / "ic_launcher.png"], stdout=subprocess.DEVNULL)


def build_apk(data: Path, products: Path) -> Path:
    stage = OUT / "apk"
    if stage.exists():
        shutil.rmtree(stage)
    (stage / "classes").mkdir(parents=True)
    (stage / "dex").mkdir()
    (stage / "lib/lib/arm64-v8a").mkdir(parents=True)
    (stage / "assets").mkdir()
    # A fresh clone has no tracked resources (git keeps no empty folders); the generated icon fills res/.
    (stage / "res").mkdir(parents=True, exist_ok=True)
    if (ROOT / "android/app/res").is_dir():
        shutil.copytree(ROOT / "android/app/res", stage / "res", dirs_exist_ok=True)
    make_icon(stage)
    engine = products / "libyeonggeoljeon.so"
    jni = build_jni(products)
    libs = [engine, jni, *runtime_libraries(engine, [jni])]
    for lib in libs:
        shutil.copy2(lib, stage / "lib/lib/arm64-v8a" / lib.name)
    sources = sorted((ROOT / "android/app/src").rglob("*.java"))
    run(["javac", "--release", "17", "-cp", ANDROID_JAR, "-d", stage / "classes", *sources])
    classes = sorted((stage / "classes").rglob("*.class"))
    run([BUILD_TOOLS / "d8", "--lib", ANDROID_JAR, "--min-api", "28", "--output", stage / "dex", *classes])
    shutil.copytree(data, stage / "assets/GameData")
    run([BUILD_TOOLS / "aapt2", "compile", "--dir", stage / "res", "-o", stage / "res.zip"])
    base = stage / "base.apk"
    run([BUILD_TOOLS / "aapt2", "link", "-o", base, "-I", ANDROID_JAR, "--manifest", ROOT / "android/app/AndroidManifest.xml",
         "--min-sdk-version", "28", "--target-sdk-version", "35", "-A", stage / "assets", stage / "res.zip"])
    shutil.copy2(stage / "dex/classes.dex", stage / "lib/classes.dex")
    run(["zip", "-q", "-r", base, "classes.dex", "lib"], cwd=stage / "lib")
    aligned = stage / "aligned.apk"
    run([BUILD_TOOLS / "zipalign", "-f", "-p", "4", base, aligned])
    keystore = OUT / "debug.keystore"
    if not keystore.exists():
        run(["keytool", "-genkeypair", "-keystore", keystore, "-storepass", "android", "-keypass", "android", "-alias", "debug",
             "-keyalg", "RSA", "-keysize", "2048", "-validity", "10000", "-dname", "CN=Yeonggeoljeon Debug"], stdout=subprocess.DEVNULL)
    final = OUT / "Yeonggeoljeon.apk"
    run([BUILD_TOOLS / "apksigner", "sign", "--ks", keystore, "--ks-pass", "pass:android", "--key-pass", "pass:android",
         "--out", final, aligned])
    return final


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--configuration", choices=["debug", "release"], default="release")
    parser.add_argument("--data", type=Path, default=ROOT / "build/ipad/GameData", help="prepared GameData folder")
    parser.add_argument("--swift-only", action="store_true")
    parser.add_argument("--install", metavar="SERIAL", help="adb serial of the tablet to install on")
    args = parser.parse_args()
    products = build_swift(args.configuration)
    if args.swift_only:
        print(products)
        return
    apk = build_apk(args.data.resolve(), products)
    print(apk)
    if args.install:
        run(["adb", "-s", args.install, "install", "-r", apk])


if __name__ == "__main__":
    main()
